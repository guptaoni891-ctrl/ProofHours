// Writes docs/v2-abi.js from the compiled Foundry artifacts so the front end always matches the contracts.
// Run after `forge build`:  node script/export-v2-abi.js
const fs = require("fs");
const path = require("path");
const out = path.join(__dirname, "..", "out");
const abi = (file, name) => JSON.parse(fs.readFileSync(path.join(out, file, `${name}.json`), "utf8")).abi;
const data = { ledger: abi("ProofHoursLedger.sol", "ProofHoursLedger"), badges: abi("ProofHoursBadges.sol", "ProofHoursBadges") };
const target = path.join(__dirname, "..", "docs", "v2-abi.js");
fs.writeFileSync(target, `// Generated by script/export-v2-abi.js from out/ — do not edit by hand.\nwindow.V2_ABI = ${JSON.stringify(data)};\n`);
console.log(`wrote ${path.relative(process.cwd(), target)} (${data.ledger.length} ledger + ${data.badges.length} badge ABI entries)`);
